def _walk(items, parent_id, teacher_id, ks, created, parent_name="",
          tree_type="knowledge", depth=0):
    """按结构建树（同名同名层级跳过；--force 模式下树已清空，全建）。
    category：模块=「模块」，章节=模块名，知识点=章节名，考点=知识点名。
    description：全部入库（修复批次21 漏传 bug）。"""
    for node in items:
        name = node["name"]
        existing = ks.find_child(teacher_id, parent_id, name, tree_type=tree_type)
        if existing:
            node_id = existing["node_id"]
            created["skip"] += 1
        else:
            if depth == 0:
                cat = "模块"
            elif depth == 1:
                cat = parent_name
            else:
                cat = parent_name  # 知识点=章节名；考点=知识点名（parent_name 即父名）
            node_id = ks.create_node(teacher_id, name, parent_id=parent_id,
                                     category=cat,
                                     description=node.get("desc") or "",
                                     tree_type=tree_type)["node_id"]
            created["new"] += 1
        _walk(node.get("children") or [], node_id, teacher_id, ks, created, name,
              tree_type, depth + 1)


def build(force=False):
    ks: KnowledgeStore = get_knowledge_store()
    stats = {}
    trees = (YULUN, PANDUAN, ZILIAO, SHULIANG, CHANGSHI, SHENLUN, MIANSHI)
    for tid in ("T001", "T002"):
        if force:
            for tree_type in ("knowledge", "qtype"):
                deleted = _delete_tree(ks, tid, tree_type)
                stats[f"{tid}:{tree_type}:deleted"] = deleted
        c = {"new": 0, "skip": 0}
        for tree in trees:
            _walk([tree], "", tid, ks, c)
        stats[f"{tid}:knowledge"] = c
        qc = {"new": 0, "skip": 0}
        _walk(QTYPES, "", tid, ks, qc, tree_type="qtype")
        stats[f"{tid}:qtype"] = qc
    return stats


def _delete_tree(ks, teacher_id, tree_type):
    """整树删除：从顶层模块起按子树批量删（subtree_ids 含自身）。"""
    n = 0
    for root in ks.get_tree(teacher_id, "", tree_type)["nodes"]:
        ids = ks.subtree_ids(teacher_id, root["node_id"])
        if ids:
            ks.batch_delete(ids)
            n += len(ids)
    return n


