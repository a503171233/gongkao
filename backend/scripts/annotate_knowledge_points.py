# 图形推理图片标记（题干含内嵌图片且无文字特征时用）
IMG_MARK = "![图"


def build_leaf_set(conn: sqlite3.Connection, teacher_id: str) -> set[str]:
    rows = conn.execute(
        "SELECT name FROM knowledge_nodes WHERE tree_type='knowledge' AND teacher_id=?",
        (teacher_id,)).fetchall()
    return {r[0] for r in rows}


def annotate(text: str, category: str) -> str | None:
    """返回命中的叶子名（特征词最长者），无命中返回 None。"""
    best_leaf, best_len = None, 0
    for leaf, words in FEATURES:
        for w in words:
            if w in text and len(w) > best_len:
                best_leaf, best_len = leaf, len(w)
                break  # 该叶子的其余词更短或等长，不必再试
    return best_leaf


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="写库（默认 dry-run）")
    ap.add_argument("--teacher", default="T001")
    args = ap.parse_args()

    db_path = Path(str(Config.data_dir)) / "study.db"
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    leaves = build_leaf_set(conn, args.teacher)
    missing = {leaf for leaf, _ in FEATURES} - leaves
    if missing:
        print(f"! 映射表引用了 {len(missing)} 个不存在的叶子（跳过）：{sorted(missing)[:6]}...")
    active_features = [(l, w) for l, w in FEATURES if l in leaves]

    rows = conn.execute(
        "SELECT id, question, options, analysis, category FROM question_bank "
        "WHERE teacher_id=? AND (knowledge_point IS NULL OR knowledge_point='')",
        (args.teacher,)).fetchall()
    stats: dict[str, int] = {}
    updates: list[tuple[str, int]] = []
    unmatched: list[tuple[int, str]] = []
    for r in rows:
        text = f"{r['question'] or ''} {r['options'] or ''} {r['analysis'] or ''}"
        leaf = annotate(text, r["category"] or "")
        if leaf:
            stats[leaf] = stats.get(leaf, 0) + 1
            updates.append((leaf, r["id"]))
        else:
            unmatched.append((r["id"], (r["question"] or "")[:40].replace("\n", " ")))

    total = len(rows)
    hit = len(updates)
    print(f"题目总数（待标注）：{total}")
    print(f"规则命中：{hit}（覆盖率 {hit * 100 // max(total, 1)}%）")
    print(f"未命中：{total - hit}（多为图形推理/类比/纯图片题，留待 LLM 层）")
    print("\n按知识点分布（Top 20）：")
    for leaf, n in sorted(stats.items(), key=lambda x: -x[1])[:20]:
        print(f"  {leaf}: {n}")
    if unmatched:
        print("\n未命中样例（前 8）：")
        for qid, q in unmatched[:8]:
            print(f"  #{qid} {q}")

    if args.apply and updates:
        with conn:
            conn.executemany(
                "UPDATE question_bank SET knowledge_point=? WHERE id=?", updates)
        print(f"\n✅ 已写入 {len(updates)} 题 knowledge_point")
    elif not args.apply:
        print("\n(dry-run 未写库，加 --apply 生效)")
    conn.close()


if __name__ == "__main__":
    main()
